            Blog::create([
                'title'        => $article['title'],
                'slug'         => $slug,
                'category'     => $article['category'],
                'tags'         => $article['tags'],
                'excerpt'      => $article['excerpt'],
                'content'      => trim($article['content']),
                'cover_image'  => $article['cover_image'],
                'author_id'    => null,
                'is_published' => true,
                'published_at' => now()->subDays(rand(1, 14)),
                'views_count'  => rand(10, 80),
                'sort_order'   => 0,
            ]);

